export function getShotBySceneId(sceneId: string): StoryShot | undefined {
  return STORYBOARD.find((s) => s.sceneId === sceneId)
}

export function getShotByProgress(progress: number): StoryShot {
  const p = Math.min(1, Math.max(0, progress))
  for (const shot of STORYBOARD) {
    if (p >= shot.startT && p < shot.endT) return shot
  }
  return STORYBOARD[STORYBOARD.length - 1]
}

export function getTotalDemoDuration(speed: 'normal' | 'slow' = 'normal'): number {
  const mult = speed === 'slow' ? 1.4 : 1.0
  return Math.round(
    STORYBOARD.reduce((acc, shot) => acc + (shot.holdDuration * mult + shot.transitionDuration), 0)
  )
}

